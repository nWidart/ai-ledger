"""The committed build in src/ai_ledger/web/ matches its sources: recomputes the hash web/scripts/stamp.mjs writes to
src/ai_ledger/web/source-hash.txt."""
import hashlib
import os
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "web")
BUILD = os.path.join(ROOT, "src", "ai_ledger", "web")
SKIP = {"src/__fixtures__"}  # regenerated by tests/test_web_fixtures.py; the build never reads it
EXTRA = ["index.html", "package-lock.json", "vite.config.ts"]


def source_files(web=WEB):
    out = []
    for root, dirs, files in os.walk(os.path.join(web, "src")):
        rel = os.path.relpath(root, web).replace(os.sep, "/")
        dirs[:] = [d for d in dirs if not d.startswith(".") and f"{rel}/{d}" not in SKIP]
        out += [f"{rel}/{f}" for f in files if not f.startswith(".")]
    return sorted(out + EXTRA)


def source_hash(web=WEB):
    """sha256 over, per file in sorted order: path, NUL, byte length, NUL, bytes. Same as stamp.mjs."""
    h = hashlib.sha256()
    for f in source_files(web):
        with open(os.path.join(web, f), "rb") as fh:
            data = fh.read()
        h.update(f"{f}\0{len(data)}\0".encode())
        h.update(data)
    return h.hexdigest()


class WebBuildTest(unittest.TestCase):
    def test_build_matches_sources(self):
        stamp = os.path.join(BUILD, "source-hash.txt")
        self.assertTrue(os.path.exists(stamp), "src/ai_ledger/web/ is missing: run `npm run build` in web/")
        with open(stamp) as fh:
            self.assertEqual(fh.read().strip(), source_hash(),
                             "src/ai_ledger/web/ is stale: run `npm run build` in web/ and commit src/ai_ledger/web/")


if __name__ == "__main__":
    unittest.main()

"""Writes API payloads from the test_metrics fixture to web/src/__fixtures__/, serialized as app.py does, so the frontend
can type-check them against web/src/api.ts and render the pages from them. Each file is a TypeScript module whose body is
the JSON payload `satisfies` its type, so tsc checks literals, tuples and missing or extra fields. A file is rewritten only
when its content changes."""
import json
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import test_metrics as tm  # noqa: E402  (puts the repo root on sys.path; imported whole so its tests don't run twice)
import metrics  # noqa: E402
import test_limits as tl  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "web", "src", "__fixtures__")


def rounded(obj):
    """Floats to 9 places: DuckDB sums floats in any order, so the last digits vary between runs."""
    if isinstance(obj, float):
        return round(obj, 9)
    if isinstance(obj, dict):
        return {k: rounded(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [rounded(v) for v in obj]
    return obj


def write(name, typ, obj):
    body = json.dumps(rounded(obj), default=str, indent=1)  # default=str as app.py: datetimes become "YYYY-MM-DD HH:MM:SS"
    text = (f"// Generated by tests/test_web_fixtures.py from the test_metrics fixture. Do not edit.\n"
            f"import type {{ {typ} }} from \"../api\";\n\nexport default {body} satisfies {typ};\n")
    path = os.path.join(OUT, name)
    try:
        with open(path) as fh:
            if fh.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w") as fh:
        fh.write(text)


def limits_fixture():
    case = tl.AnalysisCase()
    case.setUp()
    try:
        return tl.page_fixture(case)
    finally:
        case.tearDown()


class WebFixturesTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        tm.MetricsTest.setUpClass()
        tm.SourceFilterTest.setUpClass()
        cls.cur = tm.MetricsTest.con.cursor()

    @classmethod
    def tearDownClass(cls):
        tm.MetricsTest.tearDownClass()
        tm.SourceFilterTest.tearDownClass()

    def test_write_fixtures(self):
        os.makedirs(OUT, exist_ok=True)
        c = self.cur
        got = {
            # 30 days: previous period and changes are set; all time with a session: they are null and the drill-in is in.
            "usage.ts": ("UsagePayload", metrics.usage(c, "", 30, prices=tm.PRICES, today=tm.TODAY)),
            "usage-all.ts": ("UsagePayload", metrics.usage(c, "", 0, "s1", prices=tm.PRICES, today=tm.TODAY, automated=True)),
            "sessions.ts": ("SessionsPage", metrics.session_list(c, prices=tm.PRICES, today=tm.TODAY)),
            "session.ts": ("SessionDetail", metrics.session(c, "s1", prices=tm.PRICES)),
            # A Claude and a Codex session on one day, filtered to Codex.
            "usage-codex.ts": ("UsagePayload", metrics.usage(tm.SourceFilterTest.con.cursor(), "", 0, prices=tm.PRICES,
                                                             today=tm.TODAY, source="codex")),
            "errors.ts": ("ErrorsPayload", metrics.errors_payload(c, "2026-11-05T12:00:00+00:00", today=tm.TODAY)),
            "limits.ts": ("LimitsPayload", limits_fixture()),
        }
        for name, (typ, obj) in got.items():
            write(name, typ, obj)
        self.assertIn("daily_work", got["usage.ts"][1])
        self.assertEqual(sorted(f for f in os.listdir(OUT) if not f.startswith(".")), sorted(got))


if __name__ == "__main__":
    unittest.main()

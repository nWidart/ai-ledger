"""Writes API payloads from the test_metrics fixture to web/src/__fixtures__/, serialized as app.py does, so the frontend
can type-check them against web/src/api.ts and render the pages from them. Each file is a TypeScript module whose body is
the JSON payload `satisfies` its type, so tsc checks literals, tuples and missing or extra fields. A file is rewritten only
when its content changes."""
import json
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import test_metrics as tm  # noqa: E402  (imported whole so its tests don't run twice)
from ai_ledger import metrics, store  # noqa: E402
import test_limits as tl  # noqa: E402
import test_insights as ti  # noqa: E402
import test_live as tlv  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "web", "src", "__fixtures__")


def rounded(obj):
    """Floats to 9 places: DuckDB sums floats in any order, so the last digits vary between runs."""
    if isinstance(obj, float):
        return round(obj, 9)
    if isinstance(obj, dict):
        return {k: rounded(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [rounded(v) for v in obj]
    return obj


def write(name, typ, obj):
    body = json.dumps(rounded(obj), default=str, indent=1)  # default=str as app.py: datetimes become "YYYY-MM-DD HH:MM:SS"
    text = (f"// Generated by tests/test_web_fixtures.py from the test_metrics fixture. Do not edit.\n"
            f"import type {{ {typ} }} from \"../api\";\n\nexport default {body} satisfies {typ};\n")
    path = os.path.join(OUT, name)
    try:
        with open(path) as fh:
            if fh.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w") as fh:
        fh.write(text)


def limits_fixture():
    case = tl.AnalysisCase()
    case.setUp()
    try:
        return tl.page_fixture(case)
    finally:
        case.tearDown()


def insights_fixtures():
    """The Insights payloads the page tests render: the synthetic usage-data fixture (an in-store session, a worktree
    orphan and an unknown outcome) beside two unanalysed Claude Code sessions and a Codex one; and a store with no facets."""
    case = ti.InsightsCase()
    case.setUp()
    try:
        empty = case.payload(range_days=0)
        case.session(ti.A + "1", "demo-app", "2026-11-03 09:00:00")
        store.insert(case.con.cursor(), "session_titles", ["session_id", "custom", "agent"], [(ti.A + "1", None, "Add a theme toggle")])
        case.session("c1", "demo-app", "2026-11-03 10:00:00")
        case.session("c2", "demo-app", "2026-11-04 10:00:00")
        case.session("x1", "demo-app", "2026-11-04 11:00:00", source="codex")
        case.ingest()
        case.con.execute("UPDATE session_facets SET file_mtime = TIMESTAMP '2026-11-05 18:00:00'")
        full = case.payload(range_days=0)
        for d in (empty, full):
            d["coverage"]["dir"] = "/Users/example/.claude/usage-data"
        return full, empty
    finally:
        case.tearDown()


class WebFixturesTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        tm.MetricsTest.setUpClass()
        tm.SourceFilterTest.setUpClass()
        tm.ToolDetailTest.setUpClass()
        cls.cur = tm.MetricsTest.con.cursor()

    @classmethod
    def tearDownClass(cls):
        tm.MetricsTest.tearDownClass()
        tm.SourceFilterTest.tearDownClass()
        tm.ToolDetailTest.tearDownClass()

    def test_write_fixtures(self):
        os.makedirs(OUT, exist_ok=True)
        c, t = self.cur, tm.ToolDetailTest.con.cursor()
        got = {
            # 30 days: previous period and changes are set; all time with a session: they are null and the drill-in is in.
            "usage.ts": ("UsagePayload", metrics.usage(c, "", 30, prices=tm.PRICES, today=tm.TODAY)),
            "usage-all.ts": ("UsagePayload", metrics.usage(c, "", 0, "s1", prices=tm.PRICES, today=tm.TODAY, automated=True)),
            "palette.ts": ("PalettePayload", metrics.palette(c, "", 30, tm.TODAY)),
            "sessions.ts": ("SessionsPage", metrics.session_list(c, prices=tm.PRICES, today=tm.TODAY)),
            "session.ts": ("SessionDetail", metrics.session(c, "s1", prices=tm.PRICES)),
            # A Claude and a Codex session on one day, filtered to Codex.
            "usage-codex.ts": ("UsagePayload", metrics.usage(tm.SourceFilterTest.con.cursor(), "", 0, prices=tm.PRICES,
                                                             today=tm.TODAY, source="codex")),
            "errors.ts": ("ErrorsPayload", metrics.errors_payload(c, "2026-11-05T12:00:00+00:00", today=tm.TODAY)),
            "limits.ts": ("LimitsPayload", limits_fixture()),
            # The tool inspector: Bash over 30 days (a previous period, npm at 40% failed), an MCP server and a skill.
            "tool.ts": ("ToolPayload", metrics.tool_detail(t, "tool", "Bash", "", 30, tm.TODAY)),
            "tool-mcp.ts": ("ToolPayload", metrics.tool_detail(t, "mcp", "github", "", 0, tm.TODAY)),
            "tool-skill.ts": ("ToolPayload", metrics.tool_detail(t, "skill", "ship", "", 0, tm.TODAY)),
        }
        full, empty = insights_fixtures()
        got["insights.ts"] = ("InsightsPayload", full)
        got["insights-empty.ts"] = ("InsightsPayload", empty)
        lv = tlv.page_fixtures()
        got["live.ts"] = ("LivePayload", lv["list"])
        got["live-text.ts"] = ("LivePayload", lv["list_text"])
        got["live-session.ts"] = ("LiveSession", lv["claude"])
        got["live-session-text.ts"] = ("LiveSession", lv["text"])
        got["live-session-codex.ts"] = ("LiveSession", lv["codex"])
        for name, (typ, obj) in got.items():
            write(name, typ, obj)
        self.assertIn("daily_work", got["usage.ts"][1])
        self.assertEqual(sorted(f for f in os.listdir(OUT) if not f.startswith(".")), sorted(got))


if __name__ == "__main__":
    unittest.main()
